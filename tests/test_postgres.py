class SQLTranslationTests(unittest.TestCase):
    def test_literals_and_placeholders(self):
        self.assertEqual(pg_sql("SELECT '?', ?, '50%'"), "SELECT '?', %s, '50%%'")
        self.assertIn('BYTEA', pg_sql('CREATE TABLE images (id INTEGER PRIMARY KEY, image BLOB, created REAL)'))
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY', pg_sql('CREATE TABLE images (id INTEGER PRIMARY KEY)'))
        self.assertEqual(pg_sql('INSERT OR IGNORE INTO visitors VALUES (?)'), 'INSERT INTO visitors VALUES (%s) ON CONFLICT DO NOTHING')


@unittest.skipUnless(os.environ.get('TEST_DATABASE_URL'), 'PostgreSQL de test non configuré')
class PostgresIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.url = os.environ['TEST_DATABASE_URL']
        self.store = TaskStore(self.url)
        self.addCleanup(self.store.close)
        with self.store.db:
            for table in ('actions','tasks','metadata','command_limits','media_limits','music','music_artwork','music_media','ai_replies','contact_prompts','browse_sessions','duplicate_publications'):
                self.store.db.execute('DELETE FROM ' + table)

    def test_instance_lock_prevents_second_bot(self):
        with self.assertRaises(RuntimeError):
            TaskStore(self.url)

    def test_catalogue_unicode_blob_and_large_ids(self):
        index_music(self.store,'-1001234567890',{'message_id':1,'audio':{'file_id':'audio','mime_type':'audio/mpeg','performer':'Édith Piaf','title':'La vie en rose'}})
        self.assertEqual(music_page(self.store,'-1001234567890','search','edith rose')[1],1)
        with self.store.db:
            self.store.db.execute('INSERT INTO music_artwork VALUES (?,?,?,?,?,?)',('-1001234567890',1,'key',b'\x00\xffJPEG','source',0))
        self.assertEqual(self.store.db.execute('SELECT jpeg FROM music_artwork').fetchone()[0],b'\x00\xffJPEG')

    def test_atomic_rollback(self):
        with self.assertRaises(ValueError):
            with self.store.db:
                self.store.db.execute('INSERT INTO metadata VALUES (?,?)',('rollback',1))
                raise ValueError('rollback')
        self.assertIsNone(self.store.db.execute('SELECT value FROM metadata WHERE key=?',('rollback',)).fetchone())
        self.assertEqual(self.store.db.execute('SELECT 1').fetchone(),(1,))

    def test_ingest_journal_and_retry(self):
        event={'update_id':22,'message':{'chat':{'id':9000000001,'type':'private'},'from':{'id':9000000001},'text':'/start'}}
        self.store.ingest([event,event])
        self.assertEqual(self.store.offset(),23)
        api=Mock()
        api.call.side_effect=[TelegramError(429,1),{'message_id':10}]
        journal=JournalAPI(api,self.store)
        worker=Worker(self.store,journal,lambda *_:journal.action('send','sendMessage',chat_id=9000000001,text='hello'),0,threading.Event())
        worker.process_one()
        with self.store.db:
            self.store.db.execute('UPDATE tasks SET ready=0')
        worker.process_one()
        self.assertEqual(api.call.call_count,2)
        self.assertEqual(self.store.pending_count(),0)

    def test_duplicate_confirmation_identity(self):
        message={'message_id':1,'chat':{'id':7},'from':{'id':7},'audio':{'file_name':'song.mp3','file_unique_id':'u','performer':'A','title':'B'}}
        token=create_publication(self.store,'-10042',message)
        self.assertEqual(resolve_publication(self.store,token,7,'-10042',True),'queued')
        self.assertIsInstance(self.store.db.execute('SELECT task_id FROM duplicate_publications WHERE token=?',(token,)).fetchone()[0],int)

    def test_restore_tool_never_replays_pending_tasks(self):
        from postgres_backups import create_backup, temporary_server
        from restore_postgres import restore
        import psycopg
        self.store.ingest([{'update_id':99,'message':{'chat':{'id':7,'type':'private'},'text':'hello'}}])
        with tempfile.TemporaryDirectory() as folder:
            snapshot=create_backup(self.url,folder)
            with temporary_server() as destination:
                restore(snapshot,destination)
                with psycopg.connect(destination,autocommit=True) as db:
                    self.assertEqual(db.execute('SELECT status,payload FROM app.tasks').fetchone(),('uncertain','{}'))

    def test_visitors_and_covers(self):
        visitors=StartVisitors(self.url)
        try:
            visitors.remember(9000000002)
            self.assertTrue(visitors.contains(9000000002))
        finally:
            visitors.db.close()
        from covers import CoverBatch
        with tempfile.TemporaryDirectory() as folder:
            batch=CoverBatch(Mock(),self.store,folder,'-10042',7,database_url=self.url)
            try:
                batch.mark(1,'done')
                self.assertEqual(batch.db.execute('SELECT status FROM covers WHERE message_id=?',(1,)).fetchone()[0],'done')
            finally:
                batch.db.close()

    def test_backup_restores_in_isolated_server(self):
        from postgres_backups import create_backup
        with self.store.db:
            self.store.db.execute('INSERT INTO metadata VALUES (?,?)',('backup-value',123))
        with tempfile.TemporaryDirectory() as folder:
            snapshot=create_backup(self.url,folder,keep=2)
            self.assertTrue((snapshot/'database.dump').is_file())
            import json
            metadata=json.loads((snapshot/'manifest.json').read_text())
            self.assertTrue(metadata['restore_verified'])
            self.assertGreater(metadata['tables']['app.metadata']['rows'],0)
