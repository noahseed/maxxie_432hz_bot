def identifier(value):
    if not re.fullmatch(r'[a-z_][a-z0-9_]*', value):
        raise ValueError('Identifiant SQL invalide')
    return '"' + value + '"'


def pg_sql(statement):
    """Traduction du petit dialecte historique utilisé par le dépôt, jamais de SQL utilisateur."""
    statement = statement.strip().rstrip(';')
    ignore = bool(re.match(r'INSERT OR IGNORE\b', statement, re.I))
    statement = re.sub(r'^INSERT OR IGNORE\b', 'INSERT', statement, flags=re.I)
    if re.search(r'\bINSERT OR REPLACE\b', statement, re.I):
        raise ValueError('Utiliser un UPSERT explicite')
    statement = re.sub(r'\binstr\s*\(', 'strpos(', statement, flags=re.I)
    if re.match(r'(CREATE|ALTER)\b', statement, re.I):
        statement = re.sub(r'\bid INTEGER PRIMARY KEY\b', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement, flags=re.I)
        statement = re.sub(r'\bINTEGER\b', 'BIGINT', statement, flags=re.I)
        statement = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', statement, flags=re.I)
        statement = re.sub(r'\bBLOB\b', 'BYTEA', statement, flags=re.I)
    # Preserve literal question marks and escape literal percent signs for psycopg.
    parts, quoted, index = [], False, 0
    while index < len(statement):
        char = statement[index]
        if char == "'":
            if quoted and index + 1 < len(statement) and statement[index + 1] == "'":
                parts.append("''")
                index += 2
                continue
            quoted = not quoted
        parts.append('%s' if char == '?' and not quoted else ('%%' if char == '%' else char))
        index += 1
    return ''.join(parts) + (' ON CONFLICT DO NOTHING' if ignore else '')


class Rows:
    def __init__(self, rows=()):
        self.rows = list(rows)
        self.rowcount = len(self.rows)

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchall(self):
        rows, self.rows = self.rows, []
        return rows

    def __iter__(self):
        return iter(self.rows)


class Postgres:
    def __init__(self, dsn, schema='app', readonly=False):
        if psycopg is None:
            raise RuntimeError('Installer python3-psycopg pour PostgreSQL')
        self.schema, self.lock, self.contexts = schema, threading.RLock(), []
        self.raw = psycopg.connect(dsn, autocommit=True, connect_timeout=10)
        try:
            if not readonly:
                self.raw.execute('CREATE SCHEMA IF NOT EXISTS ' + identifier(schema))
            self.raw.execute('SET search_path TO ' + identifier(schema) + ', pg_catalog')
            self.raw.execute("SET lock_timeout TO '10s'")
            if readonly:
                self.raw.execute('SET default_transaction_read_only TO on')
        except BaseException:
            self.raw.close()
            raise

    def execute(self, statement, params=()):
        with self.lock:
            pragma = re.fullmatch(r'PRAGMA table_info\((\w+)\)', statement.strip(), re.I)
            if pragma:
                return self.raw.execute('SELECT ordinal_position-1,column_name,data_type,0,column_default,0 FROM information_schema.columns WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position', (self.schema, pragma[1]))
            if statement.strip().upper().startswith('PRAGMA '):
                if not re.fullmatch(r'PRAGMA (journal_mode=WAL|synchronous=FULL|busy_timeout=\d+)', statement.strip(), re.I):
                    raise ValueError('PRAGMA non pris en charge par PostgreSQL')
                return Rows()
            if statement.strip().upper() == 'BEGIN IMMEDIATE':
                return Rows()  # The explicit connection transaction already provides atomicity.
            return self.raw.execute(pg_sql(statement), params)

    def executemany(self, statement, params):
        with self.lock:
            cursor = self.raw.cursor()
            cursor.executemany(pg_sql(statement), params)
            return cursor

    def executescript(self, script):
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

    def __enter__(self):
        self.lock.acquire()
        context = self.raw.transaction()
        try:
            context.__enter__()
            self.contexts.append(context)
        except BaseException:
            self.lock.release()
            raise
        return self

    def __exit__(self, *error):
        try:
            return self.contexts.pop().__exit__(*error)
        finally:
            self.lock.release()

    def commit(self):
        self.raw.commit()

    def close(self):
        self.raw.close()

    def exclusive(self, name):
        key = int.from_bytes(hashlib.sha256(name.encode()).digest()[:8], 'big', signed=True)
        if not self.raw.execute('SELECT pg_try_advisory_lock(%s)', (key,)).fetchone()[0]:
            self.close()
            raise RuntimeError('Une autre instance utilise déjà cette base de tâches.')


def connect(value, schema='app', readonly=False, **kwargs):
    if is_postgres(value):
        return Postgres(str(value), schema=schema, readonly=readonly)
    return sqlite3.connect(value, **kwargs)
